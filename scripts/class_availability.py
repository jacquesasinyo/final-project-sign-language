"""Class x signer availability report for the LOCAL AUTSL copy.

Counts, for every class and split, how many colour videos exist locally and
from how many signers. Used to choose the class subset (DS-02) from clip and
signer counts only -- never from model results.

Usage:
    python scripts/class_availability.py --data-root <AUTSL dir> \
        --out-md docs/class_availability.md --out-csv outputs/class_availability.csv
"""
import argparse
import csv
import hashlib
from collections import Counter, defaultdict
from pathlib import Path

from tsl.data import LABEL_FILES as SPLITS, SIGNLIST, assert_signers_disjoint, read_labels, signer_of

# Nested support tiers, based on counts only. Val and test maxima in this copy
# are 8 clips / 3 signers and 17 clips / 6 signers per class.
TIERS = [
    ("A", dict(train_clips=20, train_signers=5, val_clips=8, val_signers=3, test_clips=17, test_signers=6)),
    ("B", dict(train_clips=18, train_signers=4, val_clips=7, val_signers=3, test_clips=16, test_signers=6)),
    ("C", dict(train_clips=1, train_signers=1, val_clips=1, val_signers=1, test_clips=1, test_signers=1)),
]


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def local_videos(split_dir):
    return {p.name[: -len("_color.mp4")] for p in Path(split_dir).glob("*_color.mp4")}


def tier_of(row):
    for name, t in TIERS:
        if all(row[k] >= v for k, v in t.items()):
            return name
    return "-"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-root", required=True)
    ap.add_argument("--out-md", default="docs/class_availability.md")
    ap.add_argument("--out-csv", default="outputs/class_availability.csv")
    args = ap.parse_args()
    root = Path(args.data_root)

    with open(root / SIGNLIST, newline="", encoding="utf-8-sig") as f:
        classes = {int(r["ClassId"]): (r["TR"], r["EN"]) for r in csv.DictReader(f)}

    # counts[split][class_id][signer] = number of local colour videos
    counts = {}
    split_info = {}
    for split, label_file in SPLITS.items():
        labels = read_labels(root / label_file)
        videos = local_videos(root / split)
        unlabelled = videos - labels.keys()
        if unlabelled:
            raise SystemExit(f"{split}: {len(unlabelled)} videos have no label, e.g. {sorted(unlabelled)[:3]}")
        per_class = defaultdict(Counter)
        for sample_id in videos:
            per_class[labels[sample_id]][signer_of(sample_id)] += 1
        counts[split] = per_class
        split_info[split] = dict(
            label_file=label_file, sha=sha256(root / label_file), labels=len(labels),
            videos=len(videos), label_signers=Counter(signer_of(s) for s in labels),
            video_signers=Counter(signer_of(s) for s in videos),
        )

    try:
        assert_signers_disjoint({s: i["video_signers"] for s, i in split_info.items()})
    except ValueError as e:
        raise SystemExit(str(e))

    rows = []
    for cid, (tr, en) in sorted(classes.items()):
        row = dict(class_id=cid, tr=tr, en=en)
        for split in SPLITS:
            c = counts[split][cid]
            row[f"{split}_clips"] = sum(c.values())
            row[f"{split}_signers"] = len(c)
        train = counts["train"][cid]
        row["train_top_signer_share"] = round(max(train.values()) / sum(train.values()), 2) if train else 0.0
        row["tier"] = tier_of(row)
        rows.append(row)

    Path(args.out_csv).parent.mkdir(parents=True, exist_ok=True)
    with open(args.out_csv, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    Path(args.out_md).write_text(render(rows, split_info, counts, root), encoding="utf-8")
    print(f"Wrote {args.out_md} and {args.out_csv}")


def dist(values):
    return ", ".join(f"{k}: {n}" for k, n in sorted(Counter(values).items()))


def render(rows, split_info, counts, root):
    L = ["# Class x signer availability (local AUTSL copy)", "",
         "Generated by `scripts/class_availability.py`; do not edit by hand.",
         "Counts refer to local colour videos only.", "",
         "## Label files", "", "| Split | Label file | SHA-256 | Label rows | Local videos | Coverage |",
         "|---|---|---|---|---|---|"]
    for split, i in split_info.items():
        L.append(f"| {split} | `{i['label_file']}` | `{i['sha'][:16]}…` | {i['labels']} | {i['videos']} | "
                 f"{100 * i['videos'] / i['labels']:.1f}% |")
    L.append(f"| — | `{SIGNLIST}` | `{sha256(root / SIGNLIST)[:16]}…` | {len(rows)} classes | | |")

    L += ["", "## Signers per split (local videos / labelled samples)", "",
          "| Split | Signer | Local videos | Labelled | Classes covered | Clips per class (value: #classes) |",
          "|---|---|---|---|---|---|"]
    for split, i in split_info.items():
        for s in sorted(i["video_signers"]):
            per = [counts[split][r["class_id"]][s] for r in rows]
            L.append(f"| {split} | {s} | {i['video_signers'][s]} | {i['label_signers'][s]} | "
                     f"{sum(p > 0 for p in per)} | {dist(per)} |")

    L += ["", "## Per-class distributions (value: #classes)", "", "| Split | Clips per class | Signers per class |",
          "|---|---|---|"]
    for split in SPLITS:
        L.append(f"| {split} | {dist(r[f'{split}_clips'] for r in rows)} | "
                 f"{dist(r[f'{split}_signers'] for r in rows)} |")
    L.append("")
    L.append(f"Train share of the most frequent signer within a class: "
             f"min {min(r['train_top_signer_share'] for r in rows)}, "
             f"median {sorted(r['train_top_signer_share'] for r in rows)[len(rows) // 2]}, "
             f"max {max(r['train_top_signer_share'] for r in rows)}.")

    L += ["", "## Support tiers (minimum per class; nested, counts only)", "",
          "| Tier | train clips / signers | val clips / signers | test clips / signers | Classes |",
          "|---|---|---|---|---|"]
    for name, t in TIERS:
        n = sum(all(r[k] >= v for k, v in t.items()) for r in rows)
        L.append(f"| {name} | ≥{t['train_clips']} / ≥{t['train_signers']} | ≥{t['val_clips']} / ≥{t['val_signers']} | "
                 f"≥{t['test_clips']} / ≥{t['test_signers']} | {n} |")

    tier_a = [r for r in rows if r["tier"] == "A"]
    if tier_a:
        L += ["", "## Subset size if drawn from tier A", "",
              "| N classes | train clips (min–max possible) | val clips | test clips |", "|---|---|---|---|"]
        tr = sorted(r["train_clips"] for r in tier_a)
        val = {r["val_clips"] for r in tier_a}
        test = {r["test_clips"] for r in tier_a}
        for n in (10, 15, 20, 25, 30):
            if n <= len(tier_a):
                v = n * min(val) if len(val) == 1 else "varies"
                te = n * min(test) if len(test) == 1 else "varies"
                L.append(f"| {n} | {sum(tr[:n])}–{sum(tr[-n:])} | {v} | {te} |")

    L += ["", "## All classes", "",
          "| ID | TR | EN | train clips | train signers | top-signer share | val clips | val signers | "
          "test clips | test signers | tier |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['class_id']} | {r['tr']} | {r['en']} | {r['train_clips']} | {r['train_signers']} | "
                 f"{r['train_top_signer_share']} | {r['val_clips']} | {r['val_signers']} | {r['test_clips']} | "
                 f"{r['test_signers']} | {r['tier']} |")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    main()
