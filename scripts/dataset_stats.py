"""Dataset statistics for the selected classes (DS-08), generated from the manifest.

Writes docs/dataset_stats.md: clips per class per split, signers per split, and the
distributions of duration, frame count, fps and resolution used for PRE-00 decisions.

Usage:
    python scripts/dataset_stats.py [--config configs/default.yaml] [--out docs/dataset_stats.md]
"""
import argparse
import csv
from collections import Counter

import numpy as np

from tsl.data import LABEL_FILES
from tsl.utils import load_classes, load_config

SPLITS = list(LABEL_FILES)


def pct_row(name, values):
    v = np.asarray(values, dtype=float)
    p = np.percentile(v, [0, 5, 50, 95, 100])
    return f"| {name} | " + " | ".join(f"{x:.2f}".rstrip("0").rstrip(".") for x in p) + f" | {v.mean():.2f} |"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="configs/default.yaml")
    ap.add_argument("--out", default="docs/dataset_stats.md")
    args = ap.parse_args()
    cfg = load_config(args.config)
    classes, smoke = load_classes(cfg["classes_file"])
    with open(cfg["manifest_path"], newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    L = ["# Dataset statistics (selected 20 classes)", "",
         "Generated by `scripts/dataset_stats.py` from the manifest; do not edit by hand.", "",
         "## Clips and signers per split", "", "| Split | Clips | Signers | Signer IDs |", "|---|---|---|---|"]
    for s in SPLITS:
        r = [x for x in rows if x["split"] == s]
        ids = sorted({int(x["signer_id"]) for x in r})
        L.append(f"| {s} | {len(r)} | {len(ids)} | {', '.join(map(str, ids))} |")
    L.append(f"| total | {len(rows)} | {len({x['signer_id'] for x in rows})} | |")

    L += ["", "## Clips per class per split (signers in brackets)", "",
          "| ID | TR | EN | smoke | " + " | ".join(SPLITS) + " |", "|---|---|---|---|" + "---|" * len(SPLITS)]
    for c in classes:
        cells = []
        for s in SPLITS:
            r = [x for x in rows if x["split"] == s and int(x["class_id"]) == c["id"]]
            cells.append(f"{len(r)} ({len({x['signer_id'] for x in r})})")
        L.append(f"| {c['id']} | {c['tr']} | {c['en']} | {'yes' if c['id'] in smoke else ''} | "
                 + " | ".join(cells) + " |")

    L += ["", "## Clip properties", "", "| Split / quantity | min | p5 | median | p95 | max | mean |",
          "|---|---|---|---|---|---|---|"]
    for s in SPLITS + ["all"]:
        r = [x for x in rows if s == "all" or x["split"] == s]
        L.append(pct_row(f"{s} duration (s)", [x["duration_s"] for x in r]))
        L.append(pct_row(f"{s} frame count", [x["frame_count"] for x in r]))

    L += ["", "| Property | value: #clips |", "|---|---|",
          "| fps | " + ", ".join(f"{k}: {n}" for k, n in sorted(Counter(x["fps"] for x in rows).items())) + " |",
          "| resolution | " + ", ".join(f"{k}: {n}" for k, n in sorted(
              Counter(f"{x['width']}x{x['height']}" for x in rows).items())) + " |"]
    T = cfg["seq_len"]
    short = sum(int(x["frame_count"]) < T for x in rows)
    L += ["", f"Clips shorter than seq_len T={T} (frames repeated by PRE-03 resampling): "
              f"{short} of {len(rows)} ({100 * short / len(rows):.1f}%)."]

    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
