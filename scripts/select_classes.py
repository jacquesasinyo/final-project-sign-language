"""Choose the fixed 20-class AUTSL subset (DS-02) and the 10-class smoke-test subset.

Rule: seeded random sample of 20 from all 226 AUTSL classes. No previous TÜBİTAK
sign has an exact AUTSL class, so the overlap list is empty (see docs/decisions.md D-02).
The smoke-test subset is the first 10 classes in draw order. Selection uses only the
class list and the seed; clip counts are printed afterwards as a report, never used.

Usage:
    python scripts/select_classes.py --data-root data/raw/AUTSL --out configs/classes.yaml
"""
import argparse
import csv
import random
from pathlib import Path

SEED = 2026
N_CLASSES = 20
N_SMOKE = 10
SIGNLIST = "SignList_ClassId_TR_EN.csv"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-root", default="data/raw/AUTSL")
    ap.add_argument("--out", default="configs/classes.yaml")
    ap.add_argument("--availability-csv", default="outputs/class_availability.csv")
    ap.add_argument("--force", action="store_true", help="overwrite an existing class file")
    args = ap.parse_args()

    out = Path(args.out)
    if out.exists() and not args.force:
        raise SystemExit(f"{out} exists. Classes are chosen once (DS-02); use --force only on purpose.")

    with open(Path(args.data_root) / SIGNLIST, newline="", encoding="utf-8-sig") as f:
        classes = {int(r["ClassId"]): (r["TR"], r["EN"]) for r in csv.DictReader(f)}

    drawn = random.Random(SEED).sample(sorted(classes), N_CLASSES)
    smoke = sorted(drawn[:N_SMOKE])

    L = ["# Generated by scripts/select_classes.py; do not edit by hand (DS-02).",
         "selection_rule: >-",
         f"  Seeded random sample (random.Random({SEED}).sample) of {N_CLASSES} classes from all",
         f"  {len(classes)} AUTSL classes. No previous TUBITAK sign has an exact AUTSL class,",
         f"  so no overlap classes are forced in. Smoke test = first {N_SMOKE} classes in draw order.",
         "  Uses no validation or test results.",
         f"seed: {SEED}",
         f"pool: all {len(classes)} AUTSL classes",
         "previous_vocab_overlap: []  # see docs/decisions.md D-02",
         f"draw_order: [{', '.join(map(str, drawn))}]",
         f"smoke_test_class_ids: [{', '.join(map(str, smoke))}]",
         "classes:"]
    for cid in sorted(drawn):
        tr, en = classes[cid]
        L.append(f"  - {{id: {cid}, tr: {tr}, en: {en}}}")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"Wrote {out}")

    avail = Path(args.availability_csv)
    if avail.exists():
        with open(avail, newline="", encoding="utf-8") as f:
            rows = {int(r["class_id"]): r for r in csv.DictReader(f)}
        print("id  TR                 train clips/signers  val  test  smoke")
        for cid in sorted(drawn):
            r = rows[cid]
            print(f"{cid:<3} {r['tr']:<18} {r['train_clips']:>6}/{r['train_signers']:<13} "
                  f"{r['val_clips']:>2}/{r['val_signers']} {r['test_clips']:>2}/{r['test_signers']}  "
                  f"{'yes' if cid in smoke else ''}")


if __name__ == "__main__":
    main()
